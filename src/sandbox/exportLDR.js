/**
 * Serialize an array of placements back into a compatible LDraw .ldr
 * text. Each placement becomes one `1 <color> x y z <matrix> <file>`
 * line. Coordinates are converted back to LDU (cells * 8).
 *
 * This produces output that `parseLDR.js` can round-trip — though
 * without a renderer-level bake the matrix is currently restricted to
 * a yaw (90° increments), so only 0° / 90° / 180° / 270° are precise.
 */

const LDU_PER_CELL = 8

const colorNameToCode = {}
// Build the inverse table from LDR_COLORS in parseLDR.js. We do a simple
// hex-match at call time so a single source of truth can stay there.

const yawToMatrix = (yawRad) => {
  const c = Math.cos(yawRad)
  const s = Math.sin(yawRad)
  // Column-major: m = [a, d, g, b, e, h, c, f, i]
  // Emits the LDraw-standard Y rotation (rows [c,0,s / 0,1,0 / -s,0,c])
  // so parseLDR's matrixToYaw (a=m[0], c=m[2]) recovers the exact yaw.
  return [
    c, 0, -s,
    0, 1,  0,
    s, 0,  c
  ]
}

function ldrColorHexToCode(hex) {
  if (!hex) return 7
  const h = hex.toLowerCase()
  // Mirror the LDR_COLORS map from parseLDR.js without coupling
  const table = {
    '#1b2a34': 0, '#0055bf': 1, '#237841': 2, '#58a5ab': 3,
    '#c91a09': 4, '#a83c8a': 5, '#6d6e5c': 6, '#9b9b9b': 7,
    '#6c6e6c': 8, '#5a93db': 9, '#4b9f4a': 10, '#4ab0c5': 11,
    '#d27372': 12, '#e890a0': 13, '#fec101': 14, '#f4f4f4': 15,
    '#9aca3c': 16, '#a5ca18': 17, '#22b14d': 18, '#7cd5b4': 19,
    '#7dc1a4': 20, '#ff8e0d': 21, '#bd7d2a': 22, '#d7c599': 23,
    '#d5e0e8': 24
  }
  return table[h] ?? 7
}

export function exportToLDR(placements, { title = 'lego-sandbox-build' } = {}) {
  const lines = []
  lines.push(`0 ${title}`)
  lines.push('0 Name: ' + title)
  lines.push(`0 Generated by Lego Sandbox · ${placements.length} brick${placements.length === 1 ? '' : 's'}`)
  lines.push('')
  for (const p of placements) {
    const colorCode = ldrColorHexToCode(p.color)
    const x = ((p.x ?? 0) * LDU_PER_CELL)
    const y = ((p.y ?? 0) * LDU_PER_CELL)
    const z = ((p.z ?? 0) * LDU_PER_CELL)
    const m = yawToMatrix(p.rot ?? 0)
    const a = m[0], b = m[3], c = m[6]
    const d = m[1], e = m[4], f = m[7]
    const g = m[2], h = m[5], i = m[8]
    const partNumber = String(p.partNumber)
    lines.push(
      `1 ${colorCode} ${x} ${y} ${z} ${a} ${b} ${c} ${d} ${e} ${f} ${g} ${h} ${i} ${partNumber}.dat`
    )
  }
  return lines.join('\n') + '\n'
}